package com.example.constructors;

/** Implicit default, explicit no-argument, parameterized, overloaded, and copy constructors. */
public class ConstructorTypesDemo {
    public static void main(String[] args) {
        CompilerDefault compilerDefault = new CompilerDefault();
        Book noArgument = new Book();
        Book oneArgument = new Book("Java Basics");
        Book full = new Book("Java Collections", 420);
        Book copy = new Book(full);

        System.out.println("Compiler default: " + compilerDefault);
        System.out.println(noArgument);
        System.out.println(oneArgument);
        System.out.println(full);
        System.out.println("Copy: " + copy);
    }

    // The compiler supplies a default constructor because this class declares none.
    private static class CompilerDefault { }

    private static class Book {
        private final String title;
        private final int pages;

        Book() {
            this("Untitled", 0);
        }

        Book(String title) {
            this(title, 0);
        }

        Book(String title, int pages) {
            this.title = title;
            this.pages = pages;
        }

        // A copy constructor is a programmer-defined pattern, not generated by Java.
        Book(Book source) {
            this(source.title, source.pages);
        }

        @Override
        public String toString() {
            return title + " (" + pages + " pages)";
        }
    }
}
