package com.example.example.wrapperclasses;

/** Wrapper constants describe the range of each primitive numeric type. */
public class WrapperClass05MinMaxConstants {
    public static void main(String[] args) {
        System.out.println("Integer range: " + Integer.MIN_VALUE + " to " + Integer.MAX_VALUE);
        System.out.println("Long range: " + Long.MIN_VALUE + " to " + Long.MAX_VALUE);
        System.out.println("Byte range: " + Byte.MIN_VALUE + " to " + Byte.MAX_VALUE);
        System.out.println("Float positive infinity: " + Float.POSITIVE_INFINITY);
    }
}
